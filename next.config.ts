import { execSync } from "node:child_process";
import createMDX from "@next/mdx";
import type { NextConfig } from "next";

/** Short commit of this build: Vercel's, else the local checkout's. */
function buildSha(): string {
  const vercel = process.env.VERCEL_GIT_COMMIT_SHA;
  if (vercel) return vercel.slice(0, 7);
  try {
    return execSync("git rev-parse --short=7 HEAD", { stdio: ["ignore", "pipe", "ignore"] }).toString().trim();
  } catch {
    return "unknown";
  }
}

const nextConfig: NextConfig = {
  pageExtensions: ["ts", "tsx", "md", "mdx"],
  env: {
    // X-ray "Build details" (Hero.dc.html): the build's commit and date.
    BUILD_SHA: buildSha(),
    BUILD_DATE: new Date().toLocaleDateString("en-GB", { day: "numeric", month: "short", year: "numeric", timeZone: "UTC" }),
  },
  // Tailwind v4 via its Turbopack loader, as generated by create-next-app 16.4.
  turbopack: {
    rules: {
      "*.css": {
        loaders: ["@tailwindcss/turbopack"],
        as: "*.css",
      },
    },
  },
};

export default createMDX({})(nextConfig);
